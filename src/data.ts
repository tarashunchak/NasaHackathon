export async function loadSites(): Promise<Site[]> {
  const r = await fetch(`${base}data/sites.json`);
  if (!r.ok) throw new Error(`sites.json: HTTP ${r.status}`);
  const sites = await r.json() as Site[];
  return sites.map((site) => ({ ...site, ...siteTranslations[site.id] }));
}

/** Horizon mask: { values: number[] } with values[i] = horizon elevation (deg) at azimuth i*360/n.
 *  Generated by scripts/make_horizon.py from a LOLA DEM. Returns null when no file exists. */
export async function loadHorizon(id: string): Promise<number[] | null> {
  try {
    const r = await fetch(`${base}data/horizons/${id}.json`);
    if (!r.ok) return null;
    const j = await r.json();
    return Array.isArray(j.values) && j.values.length >= 12 ? j.values : null;
  } catch {
    return null; // dev server may answer with index.html
  }
}
